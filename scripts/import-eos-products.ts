async function run() {
  console.log(`Toplam ${EOS_PRODUCTS.length} kamera çekimi ürün işleniyor...`);

  // 1. Clean public/products directory
  if (existsSync(OUT_ROOT)) {
    rmSync(OUT_ROOT, { recursive: true, force: true });
  }
  mkdirSync(OUT_ROOT, { recursive: true });

  // 2. Ensure categories exist
  const categoriesData = [
    { slug: "yapay-agac", name: "Yapay Ağaçlar", order: 1 },
    { slug: "yapay-cicek", name: "Yapay Çiçekler", order: 2 },
    { slug: "saksi", name: "Saksılı Bitkiler & Bonsai", order: 3 },
    { slug: "yapay-guller", name: "Yapay Güller & Şakayıklar", order: 4 },
  ];

  const catMap = new Map<string, string>();
  for (const c of categoriesData) {
    const cat = await prisma.category.upsert({
      where: { slug: c.slug },
      update: { name: c.name, order: c.order },
      create: { slug: c.slug, name: c.name, order: c.order },
    });
    catMap.set(c.slug, cat.id);
  }

  const brand = await prisma.brand.upsert({
    where: { slug: "cicek-yapay" },
    update: { name: "Çiçek Yapay" },
    create: { slug: "cicek-yapay", name: "Çiçek Yapay" },
  });

  // 3. Delete all existing products and related records
  await prisma.review.deleteMany({});
  await prisma.productImage.deleteMany({});
  await prisma.variant.deleteMany({});
  await prisma.wishlist.deleteMany({});
  await prisma.product.deleteMany({});
  console.log("Eski ürünler veritabanından temizlendi.");

  // 4. Process images and insert camera products
  for (let idx = 0; idx < EOS_PRODUCTS.length; idx++) {
    const item = EOS_PRODUCTS[idx];
    const prodDir = join(OUT_ROOT, item.slug);
    mkdirSync(prodDir, { recursive: true });

    const imageRecords: { url: string; alt: string; width: number; height: number; order: number }[] = [];

    for (let i = 0; i < item.files.length; i++) {
      const srcPath = join(EOS_DIR, item.files[i]);
      const destFile = `${i + 1}.jpg`;
      const destPath = join(prodDir, destFile);

      await sharp(srcPath)
        .rotate() // EXIF auto-orient
        .resize({
          width: 800,
          height: 1200,
          fit: "cover",
          position: "center",
        })
        .jpeg({ quality: 84, mozjpeg: true })
        .toFile(destPath);

      imageRecords.push({
        url: `/products/${item.slug}/${destFile}`,
        alt: `${item.name} - Görsel ${i + 1}`,
        width: 800,
        height: 1200,
        order: i,
      });
    }

    const shortDesc = `${item.heightCm} cm boyunda, ${item.potInfo.toLowerCase()} ile birlikte gönderilen 1. sınıf gerçek dokulu ${item.name.split("–")[0].trim()}.`;
    const description = [
      `${item.name}, Çiçek Yapay atölyesinde kendi stüdyo çekimlerimizle birebir gördüğünüz formda hazırlanmıştır.`,
      `• Boyut: Yaklaşık ${item.heightCm} cm yükseklik (saksı dahil)`,
      `• Saksı & Taban: ${item.potInfo}`,
      `• Gövde Yapısı: ${item.trunkInfo}`,
      `• Yaprak / Çiçek Dokusu: ${item.foliageInfo}`,
      `• Kullanım Alanları: ${item.usageInfo}`,
      `• Bakım: Sulama, güneş ışığı veya budama gerektirmez; toz tutmayan UV dayanımlı 1. kalite malzemeden üretilmiştir.`,
    ].join("\n");

    const created = await prisma.product.create({
      data: {
        sku: item.sku,
        slug: item.slug,
        name: item.name,
        shortDesc,
        description,
        basePrice: item.price,
        discountPrice: item.discountPrice,
        stock: 15,
        categoryId: catMap.get(item.categorySlug)!,
        brandId: brand.id,
        tags: JSON.stringify([item.categorySlug, `${item.heightCm} cm`, "stüdyo çekim", "gerçek doku"]),
        isFeatured: Boolean(item.isFeatured),
        isNew: Boolean(item.isNew),
        isActive: true,
        rating: 4.9,
        reviewCount: 4,
        images: {
          create: imageRecords,
        },
        variants: {
          create: [
            {
              type: "size",
              name: `${item.heightCm} cm (Görseldeki Saksılı Tam Boy)`,
              priceDelta: 0,
              stock: 15,
              sku: `${item.sku}-STD`,
            },
          ],
        },
      },
    });

    for (let r = 0; r < REVIEW_POOL.length; r++) {
      const rev = REVIEW_POOL[(idx + r) % REVIEW_POOL.length];
      await prisma.review.create({
        data: {
          productId: created.id,
          authorName: rev.name,
          authorLocation: "İstanbul",
          rating: 5,
          title: rev.title,
          body: rev.body,
          images: "[]",
          verified: true,
          helpfulCount: 2 + r,
          status: "APPROVED",
        },
      });
    }

    console.log(`[${idx + 1}/${EOS_PRODUCTS.length}] OK: ${item.name} (${imageRecords.length} fotoğraf)`);
  }

  // Update category cover images using the new camera shots
  await prisma.category.update({
    where: { slug: "yapay-agac" },
    data: { image: "/products/dogal-ahsap-govdeli-meyveli-yapay-zeytin-agaci-185-cm/1.jpg" },
  });
  await prisma.category.update({
    where: { slug: "yapay-cicek" },
    data: { image: "/products/dogal-govdeli-pudra-pembe-sarkik-sakura-yapay-agac-180-cm/1.jpg" },
  });
  await prisma.category.update({
    where: { slug: "saksi" },
    data: { image: "/products/gri-tas-saksida-kivrimli-govdeli-yapay-cam-bonsai-agaci-155-cm/1.jpg" },
  });
  await prisma.category.update({
    where: { slug: "yapay-guller" },
    data: { image: "/products/dev-ayakli-somon-pembe-dekoratif-gul-kamelya-cicegi-170-cm/1.jpg" },
  });

  console.log("Tüm kamera çekimi ürünler başarıyla kaydedildi!");
  await prisma.$disconnect();
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
